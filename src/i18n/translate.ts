export function getStoredLanguage(): Language {
  if (typeof localStorage === 'undefined') return DEFAULT_LANGUAGE;
  return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : DEFAULT_LANGUAGE;
}

export function persistLanguage(language: Language) {
  if (typeof localStorage !== 'undefined') localStorage.setItem(STORAGE_KEY, language);
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_match, key: string) => String(params[key] ?? `{{${key}}}`));
}

export function translate(language: Language, key: string, params?: Record<string, string | number>): string {
  const template = language === 'en' ? en[key] ?? key : key;
  return interpolate(template, params);
}

export function hasTranslation(key: string): boolean {
  return key in en;
}
